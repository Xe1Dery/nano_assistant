#!/usr/bin/env node
/**
 * Assembles openclaw/reminder-scan.js from reminder-core.mjs + payload-wrapper.js.
 * The OpenClaw script payload is a single file with no imports, so the core
 * is inlined here. Run this after editing either source file, then copy the
 * result to the OpenClaw host (see README).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const core = readFileSync(join(root, "openclaw", "reminder-core.mjs"), "utf8")
  .replace(/^export /gm, "");
const wrapper = readFileSync(join(root, "openclaw", "payload-wrapper.js"), "utf8");

const banner = "/* Generated by bin/build-payload.mjs — edit the sources, not this file. */\n";
const out = `${banner}\n${core}\n${wrapper}\n`;
writeFileSync(join(root, "openclaw", "reminder-scan.js"), out);
console.log("wrote openclaw/reminder-scan.js");
